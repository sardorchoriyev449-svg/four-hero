const SUPPORTED_LANGS = ['en', 'ru'];

function getLang() {
    const saved = localStorage.getItem('gameLang');
    return SUPPORTED_LANGS.includes(saved) ? saved : 'en';
}

function setLang(lang) {
    if (!SUPPORTED_LANGS.includes(lang)) return;
    localStorage.setItem('gameLang', lang);
    applyStaticTranslations();
    if (typeof onLanguageChanged === 'function') onLanguageChanged();
}

function t(key) {
    const lang = getLang();
    return (TRANSLATIONS[lang] && TRANSLATIONS[lang][key]) || TRANSLATIONS.en[key] || key;
}

// Serverdan kelgan xabar - tarjima kaliti ("kalit" yoki "kalit|qiymat"); noma'lum bo'lsa o'zini ko'rsatamiz
function tMsg(msg) {
    if (typeof msg !== 'string' || !msg) return t('generic_error');
    const [key, arg] = msg.split('|');
    if (!TRANSLATIONS.en[key]) return msg;
    const text = t(key);
    if (text.includes('{0}')) return text.replace('{0}', arg || '');
    return arg ? text + ': ' + arg : text;
}
// Skin nomi joriy tilda (inglizchasi - serverdagi nom)
function tSkinName(prefix, charType, skin) {
    const key = prefix + '_' + charType + '_' + skin.id;
    const lang = getLang();
    return (TRANSLATIONS[lang] && TRANSLATIONS[lang][key]) || skin.name;
}
function tMapName(mapId) { return t('map' + mapId + '_name'); }
function tMapDesc(mapId) { return t('map' + mapId + '_desc'); }
function tCharName(type) { return t('char_' + type); }

// HTML ichidagi barcha data-i18n atributli elementlarni joriy til bilan yangilaydi
function applyStaticTranslations() {
    document.querySelectorAll('[data-i18n]').forEach((el) => {
        el.textContent = t(el.getAttribute('data-i18n'));
    });
    document.querySelectorAll('[data-i18n-ph]').forEach((el) => {
        el.setAttribute('placeholder', t(el.getAttribute('data-i18n-ph')));
    });
    document.documentElement.lang = getLang();
}

document.addEventListener('DOMContentLoaded', applyStaticTranslations);
